import { IDBFactory } from "fake-indexeddb";
import { beforeEach, afterEach, expect, it, vi } from "vitest";
import { defaultTagData } from "@/constants/defaultTagData";
import { indexedDBStorage } from "@/services/storage/IndexedDBStorageService";
import { spotifyApiService } from "@/services/SpotifyApiService";
import { checkAutomaticRecordingReuse, getRecordingReuseStatus, recordingIdentityFor } from "../automaticRecordingReuse";
import { discussion39Releases, discussion39Artists } from "../../../../../scripts/tests/fixtures/discussion39";
const [a, b, c] = discussion39Releases.map(release => `spotify:track:${release.id}`);
const identity = { isrc: "GBAHS2600027", artistIds: discussion39Artists.map(artist => artist.id), durationMs: 192000, name: discussion39Releases[0].name };
const house = Object.values(defaultTagData.taxonomy.tagsById).find(tag => tag.name === "Rock")!.id;
const source = { rating: 3, energy: 4, bpm: 140, tagIds: [house], name: identity.name, dateModified: 20, recordingIdentity: identity };
beforeEach(async () => {
  delete window.__tagifyRecordingChecks;
  indexedDBStorage.resetConnection(); localStorage.clear(); localStorage.setItem("tagify:sync:account-id", "visible-recordings");
  vi.stubGlobal("indexedDB", new IDBFactory()); await indexedDBStorage.init();
  await indexedDBStorage.saveAll({ ...defaultTagData, tracks: { [a]: source } });
});
afterEach(() => { indexedDBStorage.resetConnection(); localStorage.clear(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("shows checking then reuses tagging for both exact unopened releases, extending the existing group", async () => {
  let finish!: (value: typeof identity) => void;
  const lookup = vi.spyOn(spotifyApiService, "getRecordingIdentity").mockImplementationOnce(() => new Promise(resolve => { finish = resolve; })).mockResolvedValue(identity);
  const changed = vi.fn(async () => undefined);
  const pending = checkAutomaticRecordingReuse({ uri: b, name: identity.name, details: { albumName: "USB002 REMIXES" } }, { [a]: source }, changed);
  await vi.waitFor(() => expect(lookup).toHaveBeenCalledTimes(1));
  expect(getRecordingReuseStatus(b)).toBe("checking");
  finish(identity); await pending;
  expect(getRecordingReuseStatus(b)).toBe("idle");
  const first = (await indexedDBStorage.loadAllStrict()).tracks;
  await checkAutomaticRecordingReuse({ uri: c, name: identity.name }, first, changed);
  const saved = (await indexedDBStorage.loadAllStrict()).tracks;
  expect(new Set([a, b, c].map(uri => saved[uri].recordingGroupId)).size).toBe(1);
  for (const uri of [a, b, c]) expect(saved[uri]).toMatchObject({ rating: 3, energy: 4, tagIds: [house] });
  expect(saved[a].dateModified).toBe(20);
  expect(saved[b].dateModified).toBe(first[b].dateModified);
  expect(saved[b]).toMatchObject({ albumName: "USB002 REMIXES", bpm: null });
});
it("shares in-flight lookups, bounds concurrency and keeps failed checks separate by account", async () => {
  const releases = [b, c, ...["d", "e", "f"].map(char => `spotify:track:${char.repeat(22)}`)];
  const finishes: Array<(value: typeof identity) => void> = [];
  const lookup = vi.spyOn(spotifyApiService, "getRecordingIdentity").mockImplementation(() => new Promise(resolve => { finishes.push(resolve); }));
  const requests = releases.map(uri => recordingIdentityFor(uri));
  expect(recordingIdentityFor(b)).toBe(requests[0]); await vi.waitFor(() => expect(lookup).toHaveBeenCalledTimes(3));
  finishes.splice(0).forEach(finish => finish(identity));
  await vi.waitFor(() => expect(lookup).toHaveBeenCalledTimes(5));
  finishes.splice(0).forEach(finish => finish(identity)); await Promise.all(requests);
  lookup.mockRejectedValue(new Error("Unavailable"));
  window.__tagifyRecordingChecks!.identities.clear();
  const failedUri = `spotify:track:${"z".repeat(22)}`;
  await checkAutomaticRecordingReuse({ uri: failedUri, name: identity.name }, { [a]: source }, vi.fn());
  expect(getRecordingReuseStatus(failedUri)).toBe("unavailable");
  const count = lookup.mock.calls.length;
  await checkAutomaticRecordingReuse({ uri: failedUri, name: identity.name }, { [a]: source }, vi.fn());
  expect(lookup).toHaveBeenCalledTimes(count);
  localStorage.setItem("tagify:sync:account-id", "other");
  await expect(recordingIdentityFor(b)).rejects.toThrow("Unavailable"); expect(lookup).toHaveBeenCalledTimes(count + 1);
});
it("does not infer a recording from its title or replace tagging saved during a lookup", async () => {
  const lookup = vi.spyOn(spotifyApiService, "getRecordingIdentity").mockResolvedValue({ ...identity, isrc: "GBAHS2600028", durationMs: identity.durationMs + 1 });
  await checkAutomaticRecordingReuse({ uri: b, name: identity.name }, { [a]: source }, vi.fn());
  expect(await indexedDBStorage.getTrack(b)).toBeNull();
  window.__tagifyRecordingChecks!.identities.clear();
  let finish!: (value: typeof identity) => void;
  lookup.mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  const freshUri = `spotify:track:${"g".repeat(22)}`;
  const pending = checkAutomaticRecordingReuse({ uri: freshUri, name: identity.name }, { [a]: source }, vi.fn());
  await vi.waitFor(() => expect(finish).toBeDefined());
  await indexedDBStorage.saveTrack(freshUri, { ...source, rating: 5, tagIds: [], recordingIdentity: undefined, dateModified: 99 });
  finish(identity); await pending;
  expect(await indexedDBStorage.getTrack(freshUri)).toMatchObject({ rating: 5, dateModified: 99 });
  expect((await indexedDBStorage.getTrack(freshUri))?.recordingGroupId).toBeUndefined();
});

it("does not save a match after the playlist row is recycled during its identity lookup", async () => {
  let current = true;
  let finish!: (value: typeof identity) => void;
  const lookup = vi.spyOn(spotifyApiService, "getRecordingIdentity").mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const changed = vi.fn();
  const pending = checkAutomaticRecordingReuse({ uri: b, name: identity.name }, { [a]: source }, changed, () => current);
  await vi.waitFor(() => expect(lookup).toHaveBeenCalledTimes(1));
  current = false; finish(identity); await pending;
  expect(await indexedDBStorage.getTrack(b)).toBeNull();
  expect(await indexedDBStorage.getTrack(a)).toEqual(source);
  expect(changed).not.toHaveBeenCalled();
});

it("recovers a rating-only Seventh Ciel record from observed details without a metadata request", async () => {
  const single = "spotify:track:4PkAV9y5D0Cp7XAWBmh55t", album = "spotify:track:4JJODZSD4UqV4lQfM7gnD3";
  const legacy = { rating: 5, energy: 0, bpm: 112, camelotKey: "11A", tagIds: [], dateModified: 42 };
  await indexedDBStorage.saveAll({ ...defaultTagData, tracks: { [single]: legacy } });
  const exactIdentity = { isrc: "QMDA62673614", name: "Seventh Ciel", durationMs: 370025, artistIds: ["3SEr9Sytj074YnBHmoI4Bd"] };
  const lookup = vi.spyOn(spotifyApiService, "getRecordingIdentity").mockResolvedValue(exactIdentity);
  const changed = vi.fn(async () => undefined);
  await checkAutomaticRecordingReuse({ uri: single, name: exactIdentity.name, details: { artists: "SimbaSōl" } }, { [single]: legacy }, changed);
  expect(await indexedDBStorage.getTrack(single)).toEqual({ ...legacy, name: "Seventh Ciel", artists: "SimbaSōl" });
  expect(lookup).not.toHaveBeenCalled();
  await checkAutomaticRecordingReuse({ uri: album, name: exactIdentity.name }, (await indexedDBStorage.loadAllStrict()).tracks, changed);
  expect(await indexedDBStorage.getTrack(album)).toMatchObject({ rating: 5, recordingIdentity: exactIdentity });
  expect(await indexedDBStorage.getTrack(single)).toMatchObject({ rating: 5, dateModified: 42, bpm: 112, camelotKey: "11A" });
  expect(lookup).toHaveBeenCalledTimes(2);
});
