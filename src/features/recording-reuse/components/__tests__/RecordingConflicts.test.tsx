import React from "react";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import { RecordingConflicts } from "../RecordingConflicts";
import { buildTaxonomyFromCategoryTree } from "@/utils/tagTaxonomy";
const taxonomy = buildTaxonomyFromCategoryTree([{ id: "genre", name: "Genre", subcategories: [{ id: "styles", name: "Styles", tags: [{ id: "house", name: "House" }, { id: "ambient", name: "Ambient" }] }] }]);
const house = Object.values(taxonomy.tagsById).find(tag => tag.name === "House")!.id;
const ambient = Object.values(taxonomy.tagsById).find(tag => tag.name === "Ambient")!.id;
const song = { name: "Song", artists: "Artist", rating: 3, energy: 4, bpm: null, tagIds: [house], albumName: "Original album" };
const group = { key: "song", entries: [["a", song], ["b", { ...song, rating: 5, energy: 8, tagIds: [ambient], albumName: "Compilation" }]] as [string, typeof song][] };
it("keeps review optional, combines tags by default, requires explicit rating/energy choices, and returns focus", async () => {
  const save = vi.fn().mockResolvedValue(undefined);
  render(<RecordingConflicts groups={[group]} taxonomy={taxonomy} onSave={save} />);
  expect(screen.queryByRole("dialog")).toBeNull();
  const review = screen.getByRole("button", { name: "Review" }); review.focus(); fireEvent.click(review);
  await screen.findByRole("dialog");
  const submit = screen.getByRole("button", { name: "Save choices" });
  expect(submit).toBeDisabled();
  expect(screen.getByRole("button", { name: "House" })).toHaveAttribute("aria-pressed", "true");
  fireEvent.click(screen.getByRole("radio", { name: "5 ★" }));
  fireEvent.click(screen.getByRole("radio", { name: "8" }));
  fireEvent.click(submit);
  await waitFor(() => expect(save).toHaveBeenCalledWith(group, { rating: 5, energy: 8, tagIds: [house, ambient] }));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  expect(review).toHaveFocus();
});
it("retains choices on failure and allows postponing with Escape without saving", async () => {
  const save = vi.fn().mockRejectedValue(new Error("Changed"));
  render(<RecordingConflicts groups={[group]} taxonomy={taxonomy} onSave={save} />);
  fireEvent.click(screen.getByRole("button", { name: "Review" }));
  const dialog = await screen.findByRole("dialog");
  fireEvent.click(screen.getByRole("radio", { name: "3 ★" })); fireEvent.click(screen.getByRole("radio", { name: "4" }));
  fireEvent.click(screen.getByRole("button", { name: "Ambient" }));
  fireEvent.click(screen.getByRole("button", { name: "Save choices" }));
  await screen.findByRole("alert");
  expect(screen.getByRole("button", { name: "Ambient" })).toHaveAttribute("aria-pressed", "false");
  fireEvent.keyDown(dialog, { key: "Escape" });
  expect(screen.queryByRole("dialog")).toBeNull();
  expect(save).toHaveBeenCalledTimes(1);
});
