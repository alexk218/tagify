import { writeFile } from 'node:fs/promises';
import process from 'node:process';
import { bookmarklet } from './bookmarklet.mjs';

export const bookmarkletModule = () =>
  `// Generated by scripts/rym/build-bookmarklet.mjs from scripts/rym/bookmarklet.mjs. Do not edit.\nexport const rymBookmarklet = ${JSON.stringify(bookmarklet)};\n`;

export const bookmarkletModuleUrl = new URL('../../src/shared/rym/bookmarklet.generated.ts', import.meta.url);

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(bookmarkletModuleUrl, bookmarkletModule());
  console.log(bookmarkletModuleUrl.pathname);
}
